void scalePenToDevice(QPen& pen, double mmToDevice)
{
    if (pen.style() == Qt::NoPen) {
        return;
    }

    const double widthMM = pen.widthF();
    const double deviceWidth = widthMM * mmToDevice;
    pen.setWidthF(deviceWidth > 0.0 ? deviceWidth : mmToDevice * 0.1);

    QVector<qreal> pattern = pen.dashPattern();
    if (!pattern.isEmpty()) {
        for (auto& value : pattern) {
            value *= mmToDevice;
        }
        pen.setDashPattern(pattern);
    }

    pen.setDashOffset(pen.dashOffset() * mmToDevice);
}
